const searchKeywordFor = (name) => {
  const trimmed = String(name || '').trim();
  // Better marketplace recall: drop trailing country suffix
  return trimmed.replace(/\s+India$/i, '').trim() || trimmed;
};

const brandCatalog = [];
const seenSlugs = new Set();

for (const [name, category] of RAW) {
  let slug = createSlug(name);
  if (!slug) slug = createSlug(`${name}-${category}`) || `brand-${brandCatalog.length}`;
  if (seenSlugs.has(slug)) {
    slug = `${slug}-${createSlug(category)}`;
  }
  if (seenSlugs.has(slug)) continue;
  seenSlugs.add(slug);

  brandCatalog.push({
    name,
    slug,
    category,
    searchKeyword: searchKeywordFor(name),
  });
}

